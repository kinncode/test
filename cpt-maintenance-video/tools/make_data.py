"""Precompute chart series from the thesis's formulas → data.js (window.DATA).

Everything here is computed from the thesis's own equations and parameters
(Table 4.1, 4.3, 4.5, 4.6) via tools/model.py, so the animated charts match
the thesis rather than being hand-drawn approximations.
"""
import json, os, sys
import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import model as M  # noqa: E402

ROOT = os.path.dirname(HERE)


def r(a, k=5):
    return [None if not np.isfinite(v) else float(f"{v:.{k}g}") for v in a]


def weibull(alpha, beta, t):
    R = np.exp(-(t / alpha) ** beta)
    f = beta / alpha * (t / alpha) ** (beta - 1) * R
    h = beta / alpha * (t / alpha) ** (beta - 1)
    return f, 1 - R, R, h


def curves_cost(alpha, beta, step=0.05, tmax=3000):
    t = np.arange(0, tmax + step, step)
    f, F, R, h = weibull(alpha, beta, t)
    cumR = np.concatenate([[0], np.cumsum((R[1:] + R[:-1]) / 2 * step)])
    out = {}
    with np.errstate(divide="ignore", invalid="ignore"):
        out["expected"] = (F * M.CC + R * M.CP) / cumR
        for k, (d, g, l) in M.CPT.items():
            wf = M.w(f, g)
            cw = np.concatenate([[0], np.cumsum((wf[1:] + wf[:-1]) / 2 * step)])
            tail = cw[-1] - cw
            out[k] = l * (cw * M.CC ** d + tail * M.CP ** d) / cumR
    return t, out, (f, F, R, h, cumR)


def tau_star(alpha, beta, cc, cp, delta=1.0, gamma=1.0, step=0.25, hi=1000):
    t = np.arange(step, hi + step, step)
    tt = np.arange(0, 4000 + step, step)
    f, F, R, h = weibull(alpha, beta, tt)
    cumR = np.concatenate([[0], np.cumsum((R[1:] + R[:-1]) / 2 * step)])
    if delta == 1.0 and gamma == 1.0:
        c = (F * cc + R * cp) / np.where(cumR > 0, cumR, np.nan)
    else:
        wf = M.w(f, gamma)
        cw = np.concatenate([[0], np.cumsum((wf[1:] + wf[:-1]) / 2 * step)])
        c = (cw * cc ** delta + (cw[-1] - cw) * cp ** delta) / np.where(cumR > 0, cumR, np.nan)
    m = (tt >= 1) & (tt <= hi)
    i = np.nanargmin(np.where(m, c, np.inf))
    return float(tt[i])


def main():
    D = {}
    # --- main case: Weibull(425.31, 2.88)
    t, cost, (f, F, R, h, cumR) = curves_cost(M.ALPHA, M.BETA)
    grid = np.arange(0, 1001, 5)
    idx = (grid / 0.05).astype(int)
    D["t"] = grid.tolist()
    D["pdf"] = r(f[idx]); D["cdf"] = r(F[idx]); D["rel"] = r(R[idx]); D["haz"] = r(h[idx])
    for k, v in cost.items():
        D["cost_" + k] = r(v[idx])
    D["opt"] = {}
    for k, v in cost.items():
        m = (t >= 1) & (t <= 1000)
        i = np.nanargmin(np.where(m, v, np.inf))
        D["opt"][k] = {"tau": round(float(t[i]), 2), "cost": round(float(v[i]), 1), "R": round(float(R[i]), 4)}
    # Weibull shapes for the background chapter (illustrative, same scale)
    D["shapes"] = {}
    for b in (0.7, 1.0, 2.88, 5.0):
        ff, FF, RR, hh = weibull(M.ALPHA, b, np.maximum(grid, 1e-9))
        D["shapes"][str(b)] = {"pdf": r(ff), "haz": r(hh)}
    # --- value function & weighting function (normalized x in [0,1])
    x = np.linspace(0, 1, 101)
    D["vx"] = r(x)
    D["value"] = {str(d): r(x ** d) for d in (0.5, 0.7, 0.88, 0.97, 1.0, 1.03, 1.2, 1.4)}
    p = np.linspace(0, 1, 101)
    D["wp"] = r(p)
    D["weight"] = {str(g): r(M.w(np.clip(p, 1e-9, 1 - 1e-9), g)) for g in (0.61, 0.69, 0.91, 1.0)}
    # classic TK1992 value function for gains/losses (x in [-1,1])
    xs = np.linspace(-1, 1, 201)
    D["tk_x"] = r(xs)
    D["tk_v"] = r(np.where(xs >= 0, np.abs(xs) ** 0.88, -2.25 * np.abs(xs) ** 0.88))
    # --- sensitivity: tau*(Cc), tau*(Cp)
    ccs = np.linspace(0.8e7, 3.0e7, 23)
    cps = np.linspace(1.0e6, 8.0e6, 29)
    D["sens_cc"] = r(ccs); D["sens_cp"] = r(cps)
    D["tau_cc"] = {
        "expected": [tau_star(M.ALPHA, M.BETA, c, M.CP) for c in ccs],
        "d0.97": [tau_star(M.ALPHA, M.BETA, c, M.CP, 0.97, 0.91) for c in ccs],
        "d1.03": [tau_star(M.ALPHA, M.BETA, c, M.CP, 1.03, 0.91) for c in ccs],
        "d0.8": [tau_star(M.ALPHA, M.BETA, c, M.CP, 0.8, 0.91) for c in ccs],
        "d1.2": [tau_star(M.ALPHA, M.BETA, c, M.CP, 1.2, 0.91) for c in ccs],
    }
    D["tau_cp"] = {"expected": [tau_star(M.ALPHA, M.BETA, M.CC, c) for c in cps]}
    # --- historical-data case (Table 4.5 / 4.6)
    n = np.array([6, 11, 11, 37, 47, 48, 100])
    D["hist_n"] = n.tolist()
    D["hist_F"] = r(np.cumsum(n) / n.sum())
    th, ch, _ = curves_cost(39.7338, 1.2185, step=0.05, tmax=3000)
    D["hist_opt"] = {}
    for k, v in ch.items():
        m = (th >= 1) & (th <= 1000)
        i = np.nanargmin(np.where(m, v, np.inf))
        D["hist_opt"][k] = {"tau": round(float(th[i]), 1), "cost": round(float(v[i]), 0)}
    with open(os.path.join(ROOT, "data.js"), "w") as fp:
        fp.write("// generated by tools/make_data.py from the thesis's equations and parameters\nwindow.DATA = ")
        json.dump(D, fp, separators=(",", ":"))
        fp.write(";\n")
    print(json.dumps({"opt": D["opt"], "hist_opt": D["hist_opt"]}, indent=1))
    print("tau_cc expected", D["tau_cc"]["expected"][:3], "...", D["tau_cc"]["expected"][-1])
    print("tau_cc d0.97", D["tau_cc"]["d0.97"][:3], " d1.03", D["tau_cc"]["d1.03"][:3])
    print("tau_cp expected", D["tau_cp"]["expected"][::7])


if __name__ == "__main__":
    main()
