"""Generate narration audio + timing from script.json.

For every cue: fetch zh-TW speech (Google Translate TTS endpoint), trim
silence, speed it up with rubberband, then lay all cues on one timeline.

Outputs
  build/cues/<scene>_<i>.wav   per-cue audio (24 kHz mono)
  build/narration.wav          full narration track
  timing.js                    window.TIMING for the HTML renderer
  out/subtitles.srt            subtitles
"""
import hashlib, json, os, subprocess, sys, time, urllib.parse, urllib.request, wave
import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SR = 24000
TEMPO = 1.38          # speed-up applied to the (slow) TTS voice
GAP = 0.32            # silence between cues (s)
LEAD = 0.75           # silence at scene start (s)
TAIL = 0.95           # hold after last cue (s)
CHAPTER_LEAD = 2.7    # scene-start silence when a new chapter begins (s)
FPS = 30


def fetch(text, dst):
    q = urllib.parse.urlencode({"ie": "UTF-8", "client": "gtx", "tl": "zh-TW", "q": text})
    url = "https://translate.googleapis.com/translate_tts?" + q
    for attempt in range(6):
        try:
            req = urllib.request.Request(url, headers={"User-Agent": "Mozilla/5.0"})
            data = urllib.request.urlopen(req, timeout=30).read()
            if len(data) < 1000:
                raise RuntimeError("short response")
            open(dst, "wb").write(data)
            return
        except Exception as e:  # noqa: BLE001
            wait = 2 ** attempt
            print(f"  retry {attempt + 1} in {wait}s: {e}", file=sys.stderr)
            time.sleep(wait)
    raise SystemExit(f"TTS failed for: {text}")


def process(src_mp3, dst_wav):
    af = ("silenceremove=start_periods=1:start_threshold=-48dB,areverse,"
          "silenceremove=start_periods=1:start_threshold=-48dB,areverse,"
          f"rubberband=tempo={TEMPO}:pitchq=quality:formant=preserved,"
          "afade=t=in:d=0.015")
    subprocess.run(["ffmpeg", "-v", "error", "-y", "-i", src_mp3, "-af", af,
                    "-ar", str(SR), "-ac", "1", dst_wav], check=True)


def read_wav(path):
    with wave.open(path) as w:
        a = np.frombuffer(w.readframes(w.getnframes()), dtype=np.int16).astype(np.float32) / 32768
    return a


def write_wav(path, a):
    a = np.clip(a, -1, 1)
    with wave.open(path, "w") as w:
        w.setnchannels(1); w.setsampwidth(2); w.setframerate(SR)
        w.writeframes((a * 32767).astype(np.int16).tobytes())


def srt_time(t):
    ms = int(round(t * 1000))
    return f"{ms // 3600000:02d}:{ms // 60000 % 60:02d}:{ms // 1000 % 60:02d},{ms % 1000:03d}"


def main():
    script = json.load(open(os.path.join(ROOT, "script.json"), encoding="utf-8"))
    cache = os.path.join(ROOT, "build", "tts_cache"); os.makedirs(cache, exist_ok=True)
    cues_dir = os.path.join(ROOT, "build", "cues"); os.makedirs(cues_dir, exist_ok=True)
    os.makedirs(os.path.join(ROOT, "out"), exist_ok=True)

    timing = {"fps": FPS, "scenes": []}
    clips = []  # (global_start, samples)
    t = 0.0
    prev_chapter = ""
    for sc in script:
        # the first scene of a chapter opens with a ~2.5 s chapter card
        chapter_start = bool(sc.get("chapter")) and sc["chapter"] != prev_chapter
        prev_chapter = sc.get("chapter", "")
        lead = sc.get("lead", CHAPTER_LEAD if chapter_start else LEAD)
        local = lead
        cues = []
        for i, cue in enumerate(sc["cues"]):
            say = cue.get("say", cue["t"])
            h = hashlib.sha1(say.encode()).hexdigest()[:16]
            mp3 = os.path.join(cache, h + ".mp3")
            if not os.path.exists(mp3):
                print(f"[tts] {sc['id']}#{i}: {say[:30]}…")
                fetch(say, mp3)
                time.sleep(0.4)
            wav = os.path.join(cues_dir, f"{sc['id']}_{i}.wav")
            if not os.path.exists(wav) or os.path.getmtime(wav) < os.path.getmtime(mp3):
                process(mp3, wav)
            a = read_wav(wav)
            d = len(a) / SR
            cues.append({"t": cue["t"], "s": round(local, 3), "e": round(local + d, 3)})
            clips.append((t + local, a))
            local += d + GAP
        dur = local - GAP + sc.get("tail", TAIL)
        timing["scenes"].append({"id": sc["id"], "chapter": sc.get("chapter", ""),
                                 "chapterStart": chapter_start,
                                 "start": round(t, 3), "dur": round(dur, 3), "cues": cues})
        t += dur
    total = t + 0.5
    timing["total"] = round(total, 3)

    track = np.zeros(int(total * SR) + SR, dtype=np.float32)
    for st, a in clips:
        i = int(st * SR); track[i:i + len(a)] += a
    write_wav(os.path.join(ROOT, "build", "narration.wav"), track)

    with open(os.path.join(ROOT, "timing.js"), "w", encoding="utf-8") as f:
        f.write("// generated by tools/tts.py — do not edit\nwindow.TIMING = ")
        json.dump(timing, f, ensure_ascii=False, indent=1)
        f.write(";\n")

    n = 1
    with open(os.path.join(ROOT, "out", "subtitles.srt"), "w", encoding="utf-8") as f:
        for sc in timing["scenes"]:
            for c in sc["cues"]:
                f.write(f"{n}\n{srt_time(sc['start'] + c['s'])} --> {srt_time(sc['start'] + c['e'])}\n{c['t']}\n\n")
                n += 1
    print(f"total {total:.1f}s ({total / 60:.1f} min), {n - 1} cues")


if __name__ == "__main__":
    main()
